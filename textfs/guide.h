#ifndef TEXTFS_GUIDE_H
#define TEXTFS_GUIDE_H

static const char guide[] =
    "Reading files from a Pyxis userspace service\n"
    "===========================================\n\n"
    "The text service supplies two immutable byte files: welcome and guide. "
    "The initial Development and Read-only spaces each start their own provider "
    "and publish it under the name text. Read the short introduction with "
    "'cat text://welcome', or read this document with 'cat text://guide'. "
    "These commands use the ordinary file interface. The applications do not "
    "need a special text-service reader.\n\n"
    "A URI selects a provider through the caller's own environment. The complete URI "
    "reaches the provider, which accepts an exact name after ://: welcome or "
    "guide. The name has no directory components, query parameters or fragment. "
    "For example, text://guide/extra and text://guide?mode=short do not name a "
    "file in this collection. URI spelling is case sensitive. The provider can "
    "also be published under another service name; that alias then selects the "
    "same collection through its own URI scheme.\n\n"
    "Reading and positions\n"
    "---------------------\n"
    "Every successful open returns a distinct file capability. Its size stays "
    "constant, and each read names an explicit byte offset. Reads may return "
    "fewer bytes than requested. A read at or beyond the end returns zero "
    "bytes, which is ordinary end of file. A client reading a long document "
    "continues from the number of bytes already received. This guide is larger "
    "than one IPC payload, so ordinary consumers must continue across several "
    "bounded transfers to reach its end.\n\n"
    "The file capability does not contain a shared seek position. A library "
    "stream can keep its own position and buffering while a second reader "
    "uses the same immutable bytes independently. Copying a capability keeps "
    "the same exported file alive; opening its URI again creates another "
    "export. No content changes occur between reads of either file. The "
    "provider describes the returned bytes as text/plain with UTF-8 encoding. "
    "This metadata describes content; it does not add authority.\n\n"
    "The shell can redirect these files into an existing application. For "
    "example, 'cat < text://welcome' reads from standard input using the same "
    "provider route as an explicit cat operand. 'cksum text://guide' reads "
    "all the document bytes and reports the checksum and length. 'head "
    "text://guide' reads the opening lines. A utility that only consumes "
    "native byte files can consume these exported files through the shared "
    "file library without interpreting the service protocol itself.\n\n"
    "Authority and immutability\n"
    "--------------------------\n"
    "The published service grants permission to open files for reading. Each "
    "returned file grants READ and the transport authority needed for a CALL. "
    "The kernel carries the actual invoking rights to the provider. The "
    "provider checks these rights before reading or reporting the file size. "
    "A copied capability can have reduced rights, but copying never creates "
    "new rights. An object identifier is only a selector for provider state; "
    "knowing an identifier does not authorize an operation.\n\n"
    "Both files are immutable. A writable open is rejected before allocating "
    "a file export. WRITE, RESIZE and SYNC calls on a read-only file are "
    "denied. Redirecting output to a text URI therefore fails instead of "
    "discarding the output or pretending to save it. Closing a reader only "
    "releases its capability. It does not ask the provider to flush data, "
    "and there is no writable backing store associated with these files.\n\n"
    "Environment and publication\n"
    "---------------------------\n"
    "Each process owns its environment. A launched application receives an "
    "explicitly selected snapshot of capabilities and text, with attenuated "
    "authority. Editing a child's environment cannot alter its parent's. A "
    "service started by the shell receives private endpoint-creation authority "
    "and a one-use publication endpoint. It sends its exported service to the "
    "shell. Before acknowledging startup, the shell atomically publishes the "
    "exported service slot and a private NAME.control controller. A collision "
    "under either name leaves both publications absent. Ordinary jobs receive "
    "the service slot; only trusted successors receive its controller.\n\n"
    "To publish the collection under a second name, use 'service start notes "
    "boot://textfs.pxe'. Then 'cat notes://welcome' reads the new provider's "
    "introduction. To configure that introduction, pass an ordinary startup "
    "argument: 'service start notes boot://textfs.pxe --welcome \"Notes space\"'. "
    "The configured message is the complete welcome-file content, including "
    "only the newline bytes supplied in the argument. The guide remains the "
    "same built-in document. Each provider has its own export budget.\n\n"
    "Use 'notes=$text' for a private typed copy of the same capability, or "
    "'export notes=$text' to make the copy inheritable. 'export notes' exports "
    "an existing value. Both names retain the slot's lineage and authority; "
    "the copy does not include the separate text.control controller. Names are "
    "exact and case sensitive. Each name selects one capability or text value; "
    "a name cannot simultaneously select a directory and a provider. Missing "
    "names fail instead of selecting another provider or filesystem path.\n\n"
    "Assignments create private values. For example, 'title=\"two words\"; "
    "echo \"$title\"' assigns TEXT and then passes one argument. TEXT can "
    "concatenate with literals without splitting or reparsing. Single quotes "
    "and escaped dollar signs stay literal. A CAP expansion must fill a whole "
    "word, quoted or unquoted; '$notes' passes notes:// with the captured entry. "
    "Braces permit dotted names, as in '${text.control}'. A conflicting child "
    "binding refuses launch; copy the value to another private name. Assignments "
    "are standalone commands or export operands; sequential ';' commands see "
    "earlier assignments. 'describe text://guide' reports resource metadata, "
    "and 'describe $notes' inspects the held capability. 'revoke ${text.control}' "
    "uses the explicitly named controller.\n\n"
    "Foreground external commands accept typed input and output redirection. "
    "With a writable destination, 'cat < text://guide > tmp://guide' saves this "
    "document; 'echo extra >> tmp://guide' appends instead of truncating it. "
    "A writable native FILE held in x accepts '> $x' and '>> $x'; read-only "
    "captured FILEs refuse writes.\n\n"
    "'x=$(echo hello); cat $x' captures a typed CAP and reads its content. "
    "Inline 'cat $(cat text://welcome)' passes a held CAP to the child. An "
    "eligible re-readable FILE passes without copying its bytes or charging "
    "retention again. Byte output becomes a read-only FILE. Configured "
    "defaults are 64 MiB per value and 512 MiB per session, shared by successors "
    "and panes. Crossing either limit binds an immutable TOO_LARGE failed "
    "value, never a successful prefix, and suggests writing to a file. Failed "
    "inline capture prevents the outer launch. A failure before evaluation or "
    "during publication preserves old bindings. Once evaluation starts, command "
    "failure publishes its actual result and reports failure.\n\n"
    "'guarded=$(revocable $text)' publishes a primary plus guarded.control. "
    "'svc=$(service start boot://textfs.pxe)' publishes a slot plus svc.control. "
    "These pairs publish atomically; a companion collision refuses publication. "
    "Paired services are leaf-only: delegating a launcher refuses before startup. "
    "Publication failure stops and drains the unpublished provider. An optional "
    "observation is a separate private x.status entry. Copying, exporting or "
    "unsetting a primary does not act on its companions; name them explicitly, "
    "as in '${guarded.control}' or '${x.status}'. Named 'service start NAME IMAGE' "
    "remains available for bootstrap services. Private HTTP request/response "
    "handling keeps its existing commands.\n\n"
    "Replacement and lifetime\n"
    "------------------------\n"
    "The shell can replace an existing binding with 'service replace text "
    "boot://textfs.pxe --welcome \"A new introduction\"'. Future opens use the "
    "new provider. Capabilities already obtained from the old provider keep "
    "their original immutable bytes. Replacement does not retarget a reader "
    "in the middle of a document. Removal with 'unset text' "
    "removes this shell's entry, so future jobs omit it. Already launched "
    "children keep their own entries and existing readers can finish. "
    "'unset text.control' separately removes this shell's controller; "
    "closing a slot controller does not cut its retained target.\n\n"
    "The provider keeps no private client copy after transferring a file "
    "capability in a reply. Once the last client copy and accepted operation "
    "have gone away, the kernel sends a retirement notice. The provider "
    "releases that export's state and acknowledges retirement before using "
    "its identifier again. Service retirement stops new opens. The provider "
    "continues to serve existing file exports and exits after all of them "
    "retire. An unexpected provider exit closes its exports; holding a client "
    "capability cannot keep a dead process operational.\n\n"
    "Limits and failures\n"
    "-------------------\n"
    "A single provider can own sixty-four exports on its receiver. One slot "
    "belongs to the published service, leaving sixty-three simultaneous file "
    "exports. Capability copies refer to the same export and do not allocate "
    "another slot. If all slots are in use, another open reports a limit "
    "failure. Closing an unused file lets its slot become reusable after "
    "retirement has been received and acknowledged.\n\n"
    "IPC transfers have bounded payloads and queues. A failed open never "
    "returns a usable file capability. A canceled delivered call still has "
    "a receipt which the provider must finish. A late reply cannot complete "
    "a different caller's request. Transport failures and application errors "
    "are separate: a closed endpoint or a deadline may prevent the transport "
    "from completing even when the request named a valid file. Consumers "
    "should report the failure and release capabilities they no longer need.\n";

#endif
